// Documentation website (okf/ops/website.md): Astro Starlight on GitHub Pages.
// The pages of okf/ and docs/ are copied in by scripts/sync-content.mjs;
// starlight-links-validator fails the build on every broken internal link.
import { readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import starlight from '@astrojs/starlight';
import { satteri } from '@astrojs/markdown-satteri';
import { defineConfig } from 'astro/config';
import mermaid from 'astro-mermaid';
import starlightLinksValidator from 'starlight-links-validator';
import { novaMarkdown } from './lib/markdown.mjs';
import { BASE, GITHUB, REPO_ROOT, SITE } from './lib/pages.mjs';

/** Names of the folders of the OKF bundle in the sidebar. */
const OKF_GROUPS = {
  architecture: 'Architecture',
  data: 'Data',
  features: 'Features',
  security: 'Security',
  ops: 'Operations and process',
};

/** The Decisions section: the top-level concepts, then one group per folder. */
function decisionsSidebar() {
  const okf = path.join(REPO_ROOT, 'okf');
  const entries = readdirSync(okf).sort();
  const pages = entries
    .filter((f) => f.endsWith('.md') && f !== 'index.md')
    .map((f) => `decisions/${f.slice(0, -3)}`);
  const groups = entries
    .filter((f) => statSync(path.join(okf, f)).isDirectory())
    .map((dir) => ({
      label: OKF_GROUPS[dir] ?? dir[0].toUpperCase() + dir.slice(1),
      collapsed: true,
      items: [{ autogenerate: { directory: `decisions/${dir}` } }],
    }));
  return [
    { label: 'The OKF bundle', link: '/decisions/' },
    ...pages,
    ...groups,
  ];
}

export default defineConfig({
  site: SITE,
  base: BASE,
  trailingSlash: 'always',
  markdown: {
    processor: satteri({ mdastPlugins: [novaMarkdown] }),
  },
  integrations: [
    mermaid({ autoTheme: true }),
    starlight({
      title: 'Nova Imperium',
      description:
        'A classic space strategy browser game for a group of friends: how it is built, run, tested and released.',
      social: [{ icon: 'github', label: 'GitHub', href: GITHUB }],
      editLink: { baseUrl: `${GITHUB}/edit/main/website/` },
      customCss: ['./src/styles/custom.css'],
      plugins: [
        starlightLinksValidator({
          // The docs point operators at http://localhost:8080 on purpose.
          errorOnLocalLinks: false,
          // Raw files generated by src/pages, not pages of the content.
          exclude: [`${BASE}/agents.md`, `${BASE}/llms.txt`],
        }),
      ],
      sidebar: [
        {
          label: 'Getting started',
          items: [
            'getting-started',
            'getting-started/installation',
            'getting-started/development',
          ],
        },
        {
          label: 'Contributing',
          items: [
            'contributing',
            {
              label: 'Design drafts',
              collapsed: true,
              items: [{ autogenerate: { directory: 'contributing/design' } }],
            },
          ],
        },
        { label: 'Git workflow', items: ['git-workflow'] },
        { label: 'CI and checks', items: ['ci'] },
        { label: 'Automation', items: ['automation'] },
        {
          label: 'Operations',
          items: ['operations', 'operations/configuration'],
        },
        { label: 'Decisions', items: decisionsSidebar() },
      ],
    }),
  ],
});
