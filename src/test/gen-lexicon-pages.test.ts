// The list of the pages of the Lexicanum that scripts/gen-features.ts writes
// (#426).
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  generateLexiconPages,
  LEXICON_PAGES_DIR,
  LEXICON_PAGES_FILE,
  renderLexiconPages,
  scanLexiconPages,
} from '../../scripts/gen-features.ts';

describe('the list of the pages of the Lexicanum (#426)', () => {
  let dir: string;
  const HEADER =
    '// Generated by scripts/gen-features.ts; not checked in, do not edit.\n';
  const write = (
    file: string,
    source = 'export const lexiconPage = { order: 10, page };\n',
  ) => {
    mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    writeFileSync(path.join(dir, file), source);
  };

  beforeEach(() => {
    dir = path.join(mkdtempSync(path.join(tmpdir(), 'nova-')), 'pages');
  });
  afterEach(() => rmSync(path.dirname(dir), { recursive: true, force: true }));

  it('is written before the tests run', () => {
    expect(
      readFileSync(path.join(LEXICON_PAGES_DIR, LEXICON_PAGES_FILE), 'utf8'),
    ).toBe(renderLexiconPages(scanLexiconPages(LEXICON_PAGES_DIR)));
  });

  it('is empty but valid for an empty or missing folder', () => {
    expect(scanLexiconPages(dir)).toEqual([]);
    expect(generateLexiconPages(dir)).toBe(true);
    expect(readFileSync(path.join(dir, LEXICON_PAGES_FILE), 'utf8')).toBe(
      `${HEADER}\nexport const LEXICON_PAGES = [] as const;\n`,
    );
  });

  it('imports every file that exports lexiconPage, sorted, and writes only a change', () => {
    write('spy.ts');
    write('battle.ts');
    write('index.ts', 'export const PAGES = [];\n');
    write('spy.test.ts');
    write(LEXICON_PAGES_FILE);
    write('x.ts', 'export const mylexiconPage = 1;\n');
    expect(scanLexiconPages(dir)).toEqual(['battle.ts', 'spy.ts']);
    expect(generateLexiconPages(dir)).toBe(true);
    expect(generateLexiconPages(dir)).toBe(false);
    expect(readFileSync(path.join(dir, LEXICON_PAGES_FILE), 'utf8')).toBe(
      [
        HEADER,
        "import { lexiconPage as feature_battle } from './battle.ts';",
        "import { lexiconPage as feature_spy } from './spy.ts';",
        '',
        'export const LEXICON_PAGES = [',
        "  ['battle', feature_battle],",
        "  ['spy', feature_spy],",
        '] as const;',
        '',
      ].join('\n'),
    );
  });
});
