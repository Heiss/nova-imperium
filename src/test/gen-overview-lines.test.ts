// The list of the line sources of the overview cards that scripts/gen-features.ts writes (#426).
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  generateOverviewLines,
  OVERVIEW_LINES_DIR,
  OVERVIEW_LINES_FILE,
  renderOverviewLines,
  scanOverviewLines,
} from '../../scripts/gen-features.ts';

describe('the list of the line sources of the overview cards (#426)', () => {
  let dir: string;
  const HEADER =
    '// Generated by scripts/gen-features.ts; not checked in, do not edit.\n';
  const write = (
    file: string,
    source = 'export const overviewLines = [];\n',
  ) => {
    mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    writeFileSync(path.join(dir, file), source);
  };

  beforeEach(() => {
    dir = path.join(
      mkdtempSync(path.join(tmpdir(), 'nova-')),
      'overview-cards',
    );
  });
  afterEach(() => rmSync(path.dirname(dir), { recursive: true, force: true }));

  it('is written before the tests run', () => {
    expect(
      readFileSync(path.join(OVERVIEW_LINES_DIR, OVERVIEW_LINES_FILE), 'utf8'),
    ).toBe(renderOverviewLines(scanOverviewLines(OVERVIEW_LINES_DIR)));
  });

  it('is empty but valid for an empty or missing folder', () => {
    expect(scanOverviewLines(dir)).toEqual([]);
    expect(generateOverviewLines(dir)).toBe(true);
    expect(readFileSync(path.join(dir, OVERVIEW_LINES_FILE), 'utf8')).toBe(
      `${HEADER}\nexport const OVERVIEW_LINES = [] as const;\n`,
    );
  });

  it('imports every file that exports overviewLines, sorted, and writes only a change', () => {
    write('unread.ts');
    write('attacks.ts');
    write('other.ts', 'export const other = 1;\n');
    write('attacks.test.ts');
    write(OVERVIEW_LINES_FILE);
    write('x.ts', 'export const myoverviewLines = [];\n');
    expect(scanOverviewLines(dir)).toEqual(['attacks.ts', 'unread.ts']);
    expect(generateOverviewLines(dir)).toBe(true);
    expect(generateOverviewLines(dir)).toBe(false);
    expect(readFileSync(path.join(dir, OVERVIEW_LINES_FILE), 'utf8')).toBe(
      [
        HEADER,
        "import { overviewLines as feature_attacks } from './attacks.ts';",
        "import { overviewLines as feature_unread } from './unread.ts';",
        '',
        'export const OVERVIEW_LINES = [',
        "  ['attacks', feature_attacks],",
        "  ['unread', feature_unread],",
        '] as const;',
        '',
      ].join('\n'),
    );
  });
});
