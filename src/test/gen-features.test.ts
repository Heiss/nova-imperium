  it('puts the shapes of the files that export StateShape together, sorted, and writes only a change', () => {
    mkdirSync(path.join(dir, 'state'), { recursive: true });
    writeFileSync(
      path.join(dir, 'state/market.ts'),
      'export type StateShape = { market: number };\n',
    );
    writeFileSync(
      path.join(dir, 'state/frame.ts'),
      'export type StateShape = { now: number };\n',
    );
    add('state/other.ts');
    expect(scanStateShapes(dir)).toEqual(['state/frame.ts', 'state/market.ts']);
    expect(generateStateShapes(dir)).toBe(true);
    expect(generateStateShapes(dir)).toBe(false);
    expect(readFileSync(path.join(dir, STATE_SHAPES_FILE), 'utf8')).toBe(
      [
        HEADER,
        "import type { StateShape as shape_state_frame } from './state/frame.ts';",
        "import type { StateShape as shape_state_market } from './state/market.ts';",
        '',
        'export type FullState = shape_state_frame & shape_state_market;',
        '',
      ].join('\n'),
    );
  });
