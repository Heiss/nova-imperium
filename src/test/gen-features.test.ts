import {
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  FEATURES_DIR,
  generate,
  INDEX_FILE,
  render,
  scan,
} from '../../scripts/gen-features.ts';

let dir: string;
const add = (file: string) => {
  mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
  writeFileSync(path.join(dir, file), 'export {};\n');
};
const index = () => readFileSync(path.join(dir, INDEX_FILE), 'utf8');

beforeEach(() => {
  dir = path.join(mkdtempSync(path.join(tmpdir(), 'nova-')), 'features');
});
afterEach(() => rmSync(path.dirname(dir), { recursive: true, force: true }));

describe('the feature index (#112)', () => {
  it('is empty but valid for an empty or missing folder', () => {
    const empty = [
      '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
      '',
      'export const ENTRIES = [] as const;',
      '',
      'export const MISSIONS = [] as const;',
      '',
    ].join('\n');
    expect(scan(dir)).toEqual({ entries: [], missions: [] });
    expect(generate(dir)).toBe(true);
    expect(index()).toBe(empty);
    mkdirSync(path.join(dir, 'missions'));
    expect(scan(dir)).toEqual({ entries: [], missions: [] });
  });

  it('imports one feature', () => {
    add('metal/entry.ts');
    generate(dir);
    expect(index()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        "import * as entry_metal from './metal/entry.ts';",
        '',
        'export const ENTRIES = [',
        "  ['metal', entry_metal],",
        '] as const;',
        '',
        'export const MISSIONS = [] as const;',
        '',
      ].join('\n'),
    );
  });

  it('imports two features and a mission, sorted by key', () => {
    add('sat/entry.ts');
    add('metal/entry.ts');
    add('sat/texts.de.ts');
    add('missions/spy/rules.ts');
    add('missions/attack/rules.ts');
    add('missions/attack/arrive.server.ts');
    expect(scan(dir)).toEqual({
      entries: ['metal', 'sat'],
      missions: ['attack', 'spy'],
    });
    generate(dir);
    expect(index()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        "import * as entry_metal from './metal/entry.ts';",
        "import * as entry_sat from './sat/entry.ts';",
        "import * as mission_attack from './missions/attack/rules.ts';",
        "import * as mission_spy from './missions/spy/rules.ts';",
        '',
        'export const ENTRIES = [',
        "  ['metal', entry_metal],",
        "  ['sat', entry_sat],",
        '] as const;',
        '',
        'export const MISSIONS = [',
        "  ['attack', mission_attack],",
        "  ['spy', mission_spy],",
        '] as const;',
        '',
      ].join('\n'),
    );
  });

  it('ignores files beside the folders and never lists a server part', () => {
    add('metal/entry.ts');
    add('metal/produce.server.ts');
    add('README.txt');
    add(INDEX_FILE);
    expect(scan(dir)).toEqual({ entries: ['metal'], missions: [] });
    expect(render(scan(dir))).not.toContain('server');
  });

  it('fails for a folder without its file or with a name that is no key', () => {
    add('metal/texts.de.ts');
    expect(() => scan(dir)).toThrow(`${dir}/metal has no entry.ts.`);
    rmSync(dir, { recursive: true });
    add('missions/spy/arrive.server.ts');
    expect(() => scan(dir)).toThrow(`${dir}/missions/spy has no rules.ts.`);
    rmSync(dir, { recursive: true });
    add('solar-sat/entry.ts');
    expect(() => scan(dir)).toThrow(/solar-sat: a feature folder is named/);
  });

  it('writes only when the index changed and leaves no temporary file', () => {
    add('metal/entry.ts');
    expect(generate(dir)).toBe(true);
    expect(generate(dir)).toBe(false);
    add('sat/entry.ts');
    expect(generate(dir)).toBe(true);
    expect(index()).toContain("['sat', entry_sat]");
    expect(readdirSync(dir).sort()).toEqual([INDEX_FILE, 'metal', 'sat']);
  });

  it('is generated in src/features before the tests run', () => {
    expect(readFileSync(path.join(FEATURES_DIR, INDEX_FILE), 'utf8')).toBe(
      render(scan(FEATURES_DIR)),
    );
  });
});
