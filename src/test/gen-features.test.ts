import {
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  FEATURES_DIR,
  generate,
  generateServer,
  INDEX_FILE,
  render,
  renderServer,
  scan,
  SERVER_INDEX_FILE,
} from '../../scripts/gen-features.ts';

let dir: string;
const add = (file: string) => {
  mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
  writeFileSync(path.join(dir, file), 'export {};\n');
};
/** An entry folder: its rules and its texts (#113). */
const entry = (key: string) => {
  add(`${key}/entry.ts`);
  add(`${key}/texts.de.ts`);
};
/** A mission folder: its rules, its name and its arrival (#116). */
const mission = (m: string) => {
  add(`missions/${m}/rules.ts`);
  add(`missions/${m}/texts.de.ts`);
  add(`missions/${m}/arrive.server.ts`);
};
const index = () => readFileSync(path.join(dir, INDEX_FILE), 'utf8');
const serverIndex = () =>
  readFileSync(path.join(dir, SERVER_INDEX_FILE), 'utf8');

beforeEach(() => {
  dir = path.join(mkdtempSync(path.join(tmpdir(), 'nova-')), 'features');
});
afterEach(() => rmSync(path.dirname(dir), { recursive: true, force: true }));

describe('the feature index (#112)', () => {
  it('is empty but valid for an empty or missing folder', () => {
    const empty = [
      '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
      '',
      'export const ENTRIES = [] as const;',
      '',
      'export const TEXTS = [] as const;',
      '',
      'export const MISSIONS = [] as const;',
      '',
      'export const MISSION_TEXTS = [] as const;',
      '',
    ].join('\n');
    expect(scan(dir)).toEqual({ entries: [], missions: [] });
    expect(generate(dir)).toBe(true);
    expect(index()).toBe(empty);
    mkdirSync(path.join(dir, 'missions'));
    expect(scan(dir)).toEqual({ entries: [], missions: [] });
  });

  it('imports one feature with its texts', () => {
    entry('metal');
    generate(dir);
    expect(index()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        "import * as entry_metal from './metal/entry.ts';",
        "import * as texts_metal from './metal/texts.de.ts';",
        '',
        'export const ENTRIES = [',
        "  ['metal', entry_metal],",
        '] as const;',
        '',
        'export const TEXTS = [',
        "  ['metal', texts_metal],",
        '] as const;',
        '',
        'export const MISSIONS = [] as const;',
        '',
        'export const MISSION_TEXTS = [] as const;',
        '',
      ].join('\n'),
    );
  });

  it('imports two features and a mission, sorted by key', () => {
    entry('sat');
    entry('metal');
    mission('spy');
    mission('attack');
    expect(scan(dir)).toEqual({
      entries: ['metal', 'sat'],
      missions: ['attack', 'spy'],
    });
    generate(dir);
    expect(index()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        "import * as entry_metal from './metal/entry.ts';",
        "import * as entry_sat from './sat/entry.ts';",
        "import * as texts_metal from './metal/texts.de.ts';",
        "import * as texts_sat from './sat/texts.de.ts';",
        "import * as mission_attack from './missions/attack/rules.ts';",
        "import * as mission_spy from './missions/spy/rules.ts';",
        "import * as mission_texts_attack from './missions/attack/texts.de.ts';",
        "import * as mission_texts_spy from './missions/spy/texts.de.ts';",
        '',
        'export const ENTRIES = [',
        "  ['metal', entry_metal],",
        "  ['sat', entry_sat],",
        '] as const;',
        '',
        'export const TEXTS = [',
        "  ['metal', texts_metal],",
        "  ['sat', texts_sat],",
        '] as const;',
        '',
        'export const MISSIONS = [',
        "  ['attack', mission_attack],",
        "  ['spy', mission_spy],",
        '] as const;',
        '',
        'export const MISSION_TEXTS = [',
        "  ['attack', mission_texts_attack],",
        "  ['spy', mission_texts_spy],",
        '] as const;',
        '',
      ].join('\n'),
    );
  });

  it('ignores files beside the folders and never lists a server part', () => {
    entry('metal');
    add('metal/produce.server.ts');
    add('README.txt');
    add(INDEX_FILE);
    expect(scan(dir)).toEqual({ entries: ['metal'], missions: [] });
    expect(render(scan(dir))).not.toContain('server');
  });

  it('fails for a folder without its files or with a name that is no key', () => {
    add('metal/texts.de.ts');
    expect(() => scan(dir)).toThrow(`${dir}/metal has no entry.ts.`);
    rmSync(dir, { recursive: true });
    add('metal/entry.ts');
    expect(() => scan(dir)).toThrow(`${dir}/metal has no texts.de.ts.`);
    rmSync(dir, { recursive: true });
    entry('metal');
    add('sat/entry.ts');
    expect(() => scan(dir)).toThrow(`${dir}/sat has no texts.de.ts.`);
    rmSync(dir, { recursive: true });
    add('missions/spy/arrive.server.ts');
    expect(() => scan(dir)).toThrow(`${dir}/missions/spy has no rules.ts.`);
    rmSync(dir, { recursive: true });
    entry('solar-sat');
    expect(() => scan(dir)).toThrow(/solar-sat: a feature folder is named/);
  });

  it('fails for a mission without its name or its arrival (#116)', () => {
    add('missions/spy/rules.ts');
    expect(() => scan(dir)).toThrow(`${dir}/missions/spy has no texts.de.ts.`);
    add('missions/spy/texts.de.ts');
    expect(() => scan(dir)).toThrow(
      `${dir}/missions/spy has no arrive.server.ts.`,
    );
    add('missions/spy/arrive.server.ts');
    expect(scan(dir)).toEqual({ entries: [], missions: ['spy'] });
  });

  it('lists the arrivals of the missions in their own server index (#116)', () => {
    expect(generateServer(dir)).toBe(true);
    expect(serverIndex()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        'export const MISSION_SERVERS = [] as const;',
        '',
      ].join('\n'),
    );
    entry('metal');
    mission('spy');
    mission('attack');
    expect(generateServer(dir)).toBe(true);
    expect(generateServer(dir)).toBe(false);
    expect(serverIndex()).toBe(
      [
        '// Generated by scripts/gen-features.ts; not checked in, do not edit.',
        '',
        "import * as server_attack from './missions/attack/arrive.server.ts';",
        "import * as server_spy from './missions/spy/arrive.server.ts';",
        '',
        'export const MISSION_SERVERS = [',
        "  ['attack', server_attack],",
        "  ['spy', server_spy],",
        '] as const;',
        '',
      ].join('\n'),
    );
    expect(readdirSync(dir).sort()).toEqual([
      SERVER_INDEX_FILE,
      'metal',
      'missions',
    ]);
  });

  it('writes only when the index changed and leaves no temporary file', () => {
    entry('metal');
    expect(generate(dir)).toBe(true);
    expect(generate(dir)).toBe(false);
    entry('sat');
    expect(generate(dir)).toBe(true);
    expect(index()).toContain("['sat', entry_sat]");
    expect(index()).toContain("['sat', texts_sat]");
    expect(readdirSync(dir).sort()).toEqual([INDEX_FILE, 'metal', 'sat']);
  });

  it('is generated in src/features before the tests run', () => {
    expect(readFileSync(path.join(FEATURES_DIR, INDEX_FILE), 'utf8')).toBe(
      render(scan(FEATURES_DIR)),
    );
    expect(
      readFileSync(path.join(FEATURES_DIR, SERVER_INDEX_FILE), 'utf8'),
    ).toBe(renderServer(scan(FEATURES_DIR)));
  });
});
